// Pixel patterns: + highlight, # main color, - shadow; dots stay transparent.
const PowerupIcons = (() => {
  function icon(rows, colors) {
    const canvas = document.createElement('canvas');
    canvas.width = Math.max(...rows.map(row => row.length));
    canvas.height = rows.length;
    const ctx = canvas.getContext('2d');
    ctx.fillStyle = colors.outline;
    rows.forEach((row, y) => [...row].forEach((pixel, x) => {
      if (pixel !== '.') ctx.fillRect(x - 1, y - 1, 3, 3);
    }));
    rows.forEach((row, y) => [...row].forEach((pixel, x) => {
      if (pixel === '.') return;
      ctx.fillStyle = colors[pixel];
      ctx.fillRect(x, y, 1, 1);
    }));
    return canvas;
  }

  const patterns = {
    speed: {
      colors: { outline: '#102b3b', '+': '#d5f9ff', '#': '#4dd0ff', '-': '#238ab8' },
      world: [
        '................', '........++##....', '.......++##.....', '......++##......',
        '.....++##.......', '....++##........', '...++######-....', '...######--.....',
        '.......##-......', '......##-.......', '.....##-........', '....##-.........',
        '...##...........', '...#............', '................', '................'
      ],
      map: ['.........', '.....++..', '....+#...', '...+#....', '..+####..', '....##...', '...##....', '..##.....', '..#......', '.........', '.........']
    },
    damage: {
      colors: { outline: '#3d1b17', '+': '#fff0b5', '#': '#ff9653', '-': '#bd482e' },
      world: [
        '................', '.......+........', '......++#.......', '......++#.......',
        '......++#.......', '......++#.......', '......+#-.......', '......+#-.......',
        '...+..+#-..#....', '...+#######-....', '......#--.......', '......##-.......',
        '......##-.......', '.....+###-......', '................', '................'
      ],
      map: ['.........', '....+....', '...+#....', '...+#....', '...+#....', '.+#####..', '...##....', '...##....', '..+###...', '.........', '.........']
    },
    invincible: {
      colors: { outline: '#142b23', '+': '#d5ffe3', '#': '#63df92', '-': '#288c65' },
      world: [
        '................', '................', '...++++++++++...', '...+########-...',
        '...+#------#-...', '...+#--++--#-...', '...+#--+#--#-...', '...+#++++#-#-...',
        '...+#--+#--#-...', '....+#-+#-#-....', '....+#----#-....', '.....+####-.....',
        '......+##-......', '.......+-.......', '................', '................'
      ],
      map: ['.........', '.+++++++.', '.+#####-.', '.+#-+-#-.', '.+#+++#-.', '.+#-+-#-.', '..+###-..', '...+#-...', '....-....', '.........', '.........']
    }
  };
  return Object.fromEntries(Object.entries(patterns).map(([type, pattern]) => [type, {
    world: icon(pattern.world, pattern.colors), map: icon(pattern.map, pattern.colors)
  }]));
})();
